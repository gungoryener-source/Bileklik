class MonitorText {
  const MonitorText._(this.lang, this.strings);

  final String lang;
  final Map<String, String> strings;

  static MonitorText of(String lang) => switch (lang) {
    'en' => en,
    'ar' => ar,
    'de' => de,
    _ => tr,
  };

  static const all = [tr, en, ar, de];

  String operator [](String key) => strings[key] ?? tr.strings[key] ?? key;

  /// Yer tutucuları doldurur: `f('agoMin', {'n': 5})`.
  String f(String key, Map<String, Object> args) {
    var s = this[key];
    for (final e in args.entries) {
      s = s.replaceAll('{${e.key}}', '${e.value}');
    }
    return s;
  }

