  const ClinicText._(this.lang, this.strings);

  final String lang;
  final Map<String, String> strings;

  static ClinicText of(String lang) => switch (lang) {
    'en' => en,
    'ar' => ar,
    'de' => de,
    _ => tr,
  };

  String operator [](String key) => strings[key] ?? tr.strings[key] ?? key;

  /// Yer tutucuları doldurur: `f('ageYears', {'n': 42})`.
  String f(String key, Map<String, Object> args) {
    var s = this[key];
    for (final e in args.entries) {
      s = s.replaceAll('{${e.key}}', '${e.value}');
    }
    return s;
  }

